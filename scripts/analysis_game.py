#!/usr/bin/env python3
"""
scripts/analysis_game.py
Fetches real Stockfish evaluations for the review scene and writes them as a Lua
table (renders/evals.lua) so the pure-Lua analyser can classify the game.

The game is Légal's mate (Paris, 1750) — it contains a genuine sacrifice ("!!")
and a genuine blunder ("??") followed by a forced mate, which makes it a good
end-to-end check of the annotation pipeline.

    python3 tools/stockfish_bridge.py --port 8099 &        # in another shell
    python3 scripts/analysis_game.py --port 8099 --depth 14
    lua5.4 scripts/dump_render_states.lua
"""

import argparse
import json
import os
import urllib.request

MOVES = [
    "e2e4", "e7e5", "g1f3", "b8c6", "f1c4", "d7d6",
    "b1c3", "c8g4", "h2h3", "g4h5", "f3e5", "h5d1",
    "c4f7", "e8e7", "c3d5",
]

START_FEN = "rnbqkbnr/pppppppp/8/8/8/8/PPPPPPPP/RNBQKBNR w KQkq - 0 1"
OUT = os.path.join("renders", "evals.lua")


def post(port, path, payload, token=None):
    body = json.dumps(payload).encode()
    headers = {"Content-Type": "application/json"}
    if token:
        headers["Authorization"] = "Bearer " + token
    request = urllib.request.Request(
        "http://127.0.0.1:%d%s" % (port, path), data=body, headers=headers)
    with urllib.request.urlopen(request, timeout=600) as response:
        return json.load(response)


def lua_value(value):
    if value is None:
        return "nil"
    if isinstance(value, bool):
        return "true" if value else "false"
    if isinstance(value, (int, float)):
        return ("%d" % value) if float(value) % 1 == 0 else ("%.4f" % value)
    if isinstance(value, str):
        return '"%s"' % value.replace("\\", "\\\\").replace('"', '\\"')
    if isinstance(value, list):
        return "{ " + ", ".join(lua_value(v) for v in value) + " }"
    if isinstance(value, dict):
        return "{ " + ", ".join("%s = %s" % (k, lua_value(v)) for k, v in value.items()) + " }"
    raise TypeError(type(value))


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("--port", type=int, default=8099)
    parser.add_argument("--depth", type=int, default=14)
    parser.add_argument("--token", default=None)
    parser.add_argument("--out", default=OUT)
    args = parser.parse_args()

    data = post(args.port, "/analyse",
                {"fen": START_FEN, "moves": MOVES, "depth": args.depth}, args.token)

    positions = data["positions"]
    assert len(positions) == len(MOVES) + 1, (len(positions), len(MOVES))

    lines = [
        "-- generated by scripts/analysis_game.py from Stockfish %s" % data.get("depth"),
        "return {",
        '\tdepth = %d,' % data["depth"],
        '\tgame = "Legal vs Saint Brie, Paris 1750",',
        "\tmoves = %s," % lua_value(MOVES),
        "\tevals = {",
    ]
    for entry in positions:
        lines.append("\t\t{ cp = %s, mate = %s, best_uci = %s, best_san = %s }," % (
            lua_value(entry["cp"]), lua_value(entry["mate"]),
            lua_value(entry["best_uci"]), lua_value(entry["best_san"])))
    lines += ["\t},", "}", ""]

    with open(args.out, "w") as handle:
        handle.write("\n".join(lines))

    print("%d positions at depth %d -> %s" % (len(positions), data["depth"], args.out))
    for i, entry in enumerate(positions):
        label = entry["best_san"] if entry["best_uci"] else "-"
        cp, mate = entry["cp"], entry["mate"]
        score = ("#%+d" % mate) if mate is not None else ("%+d" % (cp or 0))
        move = MOVES[i - 1] if i else "(start)"
        print("  %-2d %-7s %-8s best=%s" % (i, move, score, label))


if __name__ == "__main__":
    main()
