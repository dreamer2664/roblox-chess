--[[
	PieceLibrary.lua
	Builds one chess piece model.

	Two paths:
	  1. MeshPart  — if Config.Meshes[type].meshId is set, we use the imported
	     asset from assets/pieces/*.obj (generated by tools/make_pieces.py).
	     This is what you want in production: ~1.2-1.7k triangles per piece.
	  2. Primitives — the original primitive assembly, kept as a fallback so the
	     game is playable immediately after `rojo serve`, before any upload.

	Both paths return a Model whose parts are anchored, non-queryable (so board
	clicks always hit the tile underneath) and already positioned on the square.
]]

local ReplicatedStorage = game:GetService("ReplicatedStorage")
local Shared = ReplicatedStorage:WaitForChild("Shared")
local Config = require(Shared:WaitForChild("Config"))

local PieceLibrary = {}

local COLORS = Config.Colors

local function makePart(parent, props)
	local part = Instance.new("Part")
	part.Anchored = true
	part.CanCollide = false
	part.CanQuery = false
	part.CanTouch = false
	part.Material = Enum.Material.SmoothPlastic
	part.TopSurface = Enum.SurfaceType.Smooth
	part.BottomSurface = Enum.SurfaceType.Smooth
	part.Color = props.Color or Color3.new(1, 1, 1)
	part.Size = props.Size
	part.CFrame = props.CFrame
	part.Name = props.Name or "Part"
	part.CastShadow = props.CastShadow ~= false
	if props.Shape then part.Shape = props.Shape end
	part.Parent = parent
	return part
end

local function cylinder(parent, radius, height, y, color, name)
	return makePart(parent, {
		Name = name or "Cyl",
		Color = color,
		Size = Vector3.new(height, radius * 2, radius * 2),
		CFrame = CFrame.new(0, y, 0) * CFrame.Angles(0, 0, math.rad(90)),
	})
end

local function ball(parent, radius, y, color)
	return makePart(parent, {
		Name = "Ball",
		Color = color,
		Size = Vector3.new(radius * 2, radius * 2, radius * 2),
		CFrame = CFrame.new(0, y, 0),
		Shape = Enum.PartType.Ball,
	})
end

local function block(parent, size, cframe, color, name)
	return makePart(parent, { Name = name or "Block", Color = color, Size = size, CFrame = cframe })
end

---------------------------------------------------------------- fallbacks
local PRIMITIVES = {}

function PRIMITIVES.P(model, color)
	cylinder(model, 0.62, 0.22, 0.11, color, "Base")
	cylinder(model, 0.40, 0.12, 0.26, color, "Collar")
	cylinder(model, 0.26, 0.75, 0.70, color, "Stem")
	ball(model, 0.40, 1.25, color)
end

function PRIMITIVES.R(model, color)
	cylinder(model, 0.66, 0.24, 0.12, color, "Base")
	cylinder(model, 0.46, 1.05, 0.76, color, "Body")
	cylinder(model, 0.62, 0.20, 1.38, color, "Crown")
	for i = 0, 3 do
		local angle = math.rad(45 + i * 90)
		block(model, Vector3.new(0.30, 0.34, 0.30),
			CFrame.new(math.cos(angle) * 0.44, 1.62, math.sin(angle) * 0.44) * CFrame.Angles(0, -angle, 0),
			color, "Merlon")
	end
end

function PRIMITIVES.N(model, color)
	cylinder(model, 0.64, 0.20, 0.10, color, "Base")
	cylinder(model, 0.44, 0.14, 0.24, color, "Collar")
	local k = 1.16
	local parts = {
		{ Vector3.new(0.56, 0.34, 0.46), Vector3.new(0, 0.62, -0.02), 0 },
		{ Vector3.new(0.44, 1.00, 0.42), Vector3.new(0, 1.20, 0.02), -6 },
		{ Vector3.new(0.42, 0.46, 0.50), Vector3.new(0, 1.78, -0.16), -18 },
		{ Vector3.new(0.34, 0.32, 0.36), Vector3.new(0, 1.72, -0.46), -40 },
	}
	local facing = CFrame.Angles(0, math.rad(90), 0)
	for index, part in ipairs(parts) do
		block(model, part[1] * k,
			facing * CFrame.new(part[2] * k) * CFrame.Angles(math.rad(part[3]), 0, 0),
			color, "N" .. index)
	end
end

function PRIMITIVES.B(model, color)
	cylinder(model, 0.66, 0.24, 0.12, color, "Base")
	cylinder(model, 0.40, 0.22, 0.33, color, "Collar")
	ball(model, 0.38, 0.86, color)
	cylinder(model, 0.30, 0.55, 1.35, color, "Mitre")
	ball(model, 0.14, 1.70, color)
end

function PRIMITIVES.Q(model, color)
	cylinder(model, 0.70, 0.26, 0.13, color, "Base")
	cylinder(model, 0.44, 0.90, 0.72, color, "Body")
	cylinder(model, 0.56, 0.18, 1.24, color, "Collar")
	ball(model, 0.40, 1.55, color)
	for i = 0, 4 do
		local angle = math.rad(i * 72)
		local spike = ball(model, 0.16, 1.86, color)
		spike.Name = "Spike"
		spike.CFrame = CFrame.new(math.cos(angle) * 0.36, 1.86, math.sin(angle) * 0.36)
	end
	ball(model, 0.18, 2.02, color)
end

function PRIMITIVES.K(model, color)
	cylinder(model, 0.72, 0.26, 0.13, color, "Base")
	cylinder(model, 0.46, 0.95, 0.74, color, "Body")
	cylinder(model, 0.58, 0.18, 1.30, color, "Collar")
	ball(model, 0.40, 1.60, color)
	block(model, Vector3.new(0.18, 0.62, 0.18), CFrame.new(0, 2.12, 0), color, "CrossV")
	block(model, Vector3.new(0.46, 0.18, 0.18), CFrame.new(0, 2.20, 0), color, "CrossH")
end

---------------------------------------------------------------- public
PieceLibrary.usingMeshes = false

function PieceLibrary.hasMeshes()
	for _, spec in pairs(Config.Meshes or {}) do
		if spec.meshId and spec.meshId ~= 0 then return true end
	end
	return false
end

--[[
	build(ptype, color, parent, cframe)
		ptype  "P" "R" "N" "B" "Q" "K"
		color  "w" | "b"
		parent Folder to put the model in
		cframe where the piece's base sits (base plane, +Y up)
	Returns the Model.
]]
function PieceLibrary.build(ptype, color, parent, cframe)
	local model = Instance.new("Model")
	model.Name = color .. ptype
	model.Parent = parent

	local bodyColor = (color == "w") and COLORS.WhitePiece or COLORS.BlackPiece
	local spec = (Config.Meshes or {})[ptype]

	if spec and spec.meshId and spec.meshId ~= 0 then
		local mesh = Instance.new("MeshPart")
		mesh.Name = "Mesh"
		mesh.MeshId = "rbxassetid://" .. tostring(spec.meshId)
		mesh.Size = spec.size or Vector3.new(1, 2, 1)
		mesh.Anchored = true
		mesh.CanCollide = false
		mesh.CanQuery = false
		mesh.CanTouch = false
		mesh.Material = Enum.Material.SmoothPlastic
		mesh.Color = bodyColor
		mesh.CastShadow = true
		-- mesh origin is at the centre of its bounding box; lift it onto the square
		local height = (spec.size and spec.size.Y) or 2
		-- the meshes face +Z; both colours are turned to face their opponent, so
		-- Black gets an extra half turn on top of the configured yaw
		local yaw = math.rad((spec.yaw or 0) + ((color == "b") and 180 or 0))
		mesh.CFrame = cframe * CFrame.Angles(0, yaw, 0) * CFrame.new(0, height / 2, 0)
		mesh.Parent = model
		PieceLibrary.usingMeshes = true
	else
		local builder = PRIMITIVES[ptype]
		if builder then builder(model, bodyColor) end
		-- move every part from local space onto the square
		for _, part in ipairs(model:GetChildren()) do
			if part:IsA("BasePart") then
				part.CFrame = cframe * part.CFrame
			end
		end
	end

	if color == "w" then
		local outline = Instance.new("Highlight")
		outline.FillTransparency = 1
		outline.OutlineColor = Color3.fromRGB(110, 108, 100)
		outline.OutlineTransparency = 0.65
		outline.DepthMode = Enum.HighlightDepthMode.Occluded
		outline.Parent = model
	end

	return model
end

return PieceLibrary
